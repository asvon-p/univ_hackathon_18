from io import BytesIO
from uuid import uuid4

import pytest
from PIL import Image

from backend.tests.e2e.recommendation_flow import submit_recommendation


@pytest.mark.parametrize("live_api", [{"provider": "local", "starter_wardrobe": True}], indirect=True)
@pytest.mark.parametrize("live_frontend", [{}, {"mentor": True}], indirect=True)
def test_feedback_forms_keep_each_wardrobes_preferences_separate(live_frontend):
    ui, api, runtime = live_frontend
    response = ui.post(
        "/signup",
        data={
            "email": f"feedback-{uuid4().hex}@example.com",
            "password": "Wardrobe2026!",
            "password_confirm": "Wardrobe2026!",
        },
    )
    assert response.status_code == 303
    headers = {"Authorization": "Bearer " + ui.cookies["fitjang_token"]}
    image = BytesIO()
    Image.new("RGB", (32, 32), "navy").save(image, format="PNG")
    for category in ("top", "bottom"):
        upload = api.post(
            "/api/v1/garments",
            headers=headers,
            files={"file": ("synthetic.png", image.getvalue(), "image/png")},
        )
        assert upload.status_code == 201, upload.text
        patch = api.patch(
            f"/api/v1/garments/{upload.json()['garment_id']}",
            headers=headers,
            json={"category": category, "color": "navy", "style_candidates": ["casual"]},
        )
        assert patch.status_code == 200

    def generate(scope):
        result = submit_recommendation(ui, {"wardrobe": scope, "temp": "20"})
        assert result.status_code == 200 and "코디 1" in result.text
        assert f'data-feedback-scope="{scope}"' in result.text
        rid = result.url.path.rsplit("/", 1)[-1]
        saved = api.get(f"/api/v1/recommendations/{rid}", headers=headers).json()
        assert saved["context"]["wardrobe"] == scope
        return result, saved

    def dislike(result, text):
        saved = ui.post(
            "/recommend/feedback",
            headers={"X-Requested-With": "fetch"},
            data={
                "recommendation_id": result["recommendation_id"],
                "outfit_id": result["outfits"][0]["outfit_id"],
                "accepted": "0",
                "reason": text,
                "reason_codes": ["colors"],
            },
        )
        assert saved.status_code == 200 and saved.json()["ok"]
        page = ui.get(f"/recommend/result/{result['recommendation_id']}")
        assert 'value="0" aria-pressed="true"' in page.text
        assert text in page.text

    page, example = generate("example")
    assert "내 옷장 추천에는 영향을 주지 않아요." in page.text
    assert "선택한 이유와 의견은 다음 테스트용 옷장 추천에만 반영해요." in page.text
    dislike(example, "테스트용 의견")
    page, personal = generate("personal")
    assert "테스트용 옷장 피드백은 섞이지 않아요." in page.text
    assert personal["context"]["recent_feedback"] == []
    dislike(personal, "내 옷장 의견")
    _, next_example = generate("example")
    assert [e["reason"] for e in next_example["context"]["recent_feedback"]] == ["테스트용 의견"]
    _, next_personal = generate("personal")
    assert [e["reason"] for e in next_personal["context"]["recent_feedback"]] == ["내 옷장 의견"]
    # Saved history is not rewritten or regenerated by revisiting it.
    assert (
        api.get(f"/api/v1/recommendations/{example['recommendation_id']}", headers=headers).json()["context"][
            "recent_feedback"
        ]
        == []
    )
    assert len(api.get("/api/v1/garments", headers=headers).json()) == 11
